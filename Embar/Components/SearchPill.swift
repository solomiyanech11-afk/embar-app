import SwiftUI

extension View {
    /// Фон-пігулка для полів пошуку в плаваючих барах — однаковий на всіх
    /// поверхнях (правило консистентності контролів).
    /// Біла, як картки (surface-у панелі зливалась із фоном — фідбек
    /// 2026-07-21), + тінь і ледь помітний кант, щоб край читався
    func searchPillBackground() -> some View {
        background(
            Capsule().fill(.white)
                .overlay(Capsule().strokeBorder(.black.opacity(0.06)))
                .shadow(color: .black.opacity(0.10), radius: 3, y: 1)
        )
    }
}
