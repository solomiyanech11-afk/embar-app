//
//  Прозорий ловець «клік повз»: поки відкрите інлайн-поле («Нова стіна»,
//  «Нова папка»), клік у порожнє місце поверхні його прибирає — людина
//  передумала (фідбек 2026-08-12). Було тричі скопійовано в Стіках,
//  Нотатках і Рідері (ревʼю 2026-08-18, кластер дублювання).
//
//  ❗ Два правила, без яких ловець шкодить більше, ніж помагає:
//
//  1. opacity 0.001, а НЕ Color.clear: прозорий колір кліків не ловить
//     узагалі, а майже-прозорий ловить і лишається невидимим.
//  2. Чіпляти ЩОНАЙРАНІШЕ — до композера, барів і решти оверлеїв, щоб
//     ловець лежав ПІД ними. Пізніший .overlay лягає зверху, і тоді
//     ловець з'їдав перший клік у поле композера: чіп-поле зникало, але
//     фокус нікуди не йшов, і треба було клацати вдруге (ревʼю
//     2026-08-18, знахідка 4). Кліки в поля, що крадуть фокус, ловець
//     бачити не повинен — там поле знімає себе саме
//     (NewChipField.onChange(of: focused)).
//

import SwiftUI

extension View {
    /// Клік повз (у порожнє місце поверхні) → `action`. Ставити ДО
    /// оверлеїв із полями вводу — див. правило 2 вище
    func dismissOnTapOutside(_ active: Bool,
                             action: @escaping () -> Void) -> some View {
        overlay {
            if active {
                Color.black.opacity(0.001)
                    .onTapGesture(perform: action)
            }
        }
    }
}
